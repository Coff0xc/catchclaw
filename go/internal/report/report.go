type Summary struct {
	TotalFindings int `json:"total_findings"`
	Critical      int `json:"critical"`
	High          int `json:"high"`
	Medium        int `json:"medium"`
	Low           int `json:"low"`
	Info          int `json:"info"`
	RiskScore     int `json:"risk_score"`
}

func NewSummary(result *core.ScanResult) Summary {
	score := result.ChainScore()
	if score > 100 {
		score = 100
	}
	return Summary{
		TotalFindings: len(result.Findings),
		Critical:      result.CountBySeverity(core.Critical),
		High:          result.CountBySeverity(core.High),
		Medium:        result.CountBySeverity(core.Medium),
		Low:           result.CountBySeverity(core.Low),
		Info:          result.CountBySeverity(core.Info),
		RiskScore:     score,
	}
}

func WriteJSON(result *core.ScanResult, path string) error {
	summary := NewSummary(result)
	output, err := json.MarshalIndent(map[string]interface{}{
		"target":   result.Target,
		"findings": result.Findings,
		"summary":  summary,
		"start_at": result.StartAt,
		"end_at":   result.EndAt,
	}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, output, 0644)
}

func WriteJSONMulti(results []*core.ScanResult, path string) error {
	entries := make([]map[string]interface{}, 0, len(results))
	totalFindings := 0
	for _, r := range results {
		summary := NewSummary(r)
		totalFindings += len(r.Findings)
		entries = append(entries, map[string]interface{}{
			"target":   r.Target,
			"findings": r.Findings,
			"summary":  summary,
			"start_at": r.StartAt,
			"end_at":   r.EndAt,
		})
	}
	output, err := json.MarshalIndent(map[string]interface{}{
		"targets_scanned": len(results),
		"total_findings":  totalFindings,
		"results":         entries,
	}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, output, 0644)
}

func WriteMarkdown(result *core.ScanResult, path string) error {
	summary := NewSummary(result)
	var md strings.Builder

	md.WriteString("# CatchClaw Security Report\n\n")
	fmt.Fprintf(&md, "**Target:** %s:%d\n\n", result.Target.Host, result.Target.Port)
	if result.StartAt != "" {
		fmt.Fprintf(&md, "**Scan started:** %s\n\n", result.StartAt)
	}

	md.WriteString("## Summary\n\n")
	md.WriteString("| Metric | Value |\n|--------|-------|\n")
	fmt.Fprintf(&md, "| Total findings | %d |\n", summary.TotalFindings)
	fmt.Fprintf(&md, "| Risk score | %d/100 |\n", summary.RiskScore)
	fmt.Fprintf(&md, "| Critical | %d |\n", summary.Critical)
	fmt.Fprintf(&md, "| High | %d |\n", summary.High)
	fmt.Fprintf(&md, "| Medium | %d |\n", summary.Medium)
	fmt.Fprintf(&md, "| Low | %d |\n", summary.Low)
	fmt.Fprintf(&md, "| Info | %d |\n\n", summary.Info)

	if len(result.Findings) > 0 {
		md.WriteString("## Findings\n\n")
		for i, f := range result.Findings {
			fmt.Fprintf(&md, "### %d. [%s] %s\n\n", i+1, f.Severity.String(), f.Title)
			fmt.Fprintf(&md, "- **Module:** %s\n", f.Module)
			fmt.Fprintf(&md, "- **Severity:** %s\n", f.Severity.String())
			fmt.Fprintf(&md, "- **Description:** %s\n", f.Description)
			if f.Evidence != "" {
				fmt.Fprintf(&md, "- **Evidence:** `%s`\n", core.TruncateStr(f.Evidence, 200))
			}
			if f.Remediation != "" {
				fmt.Fprintf(&md, "- **Remediation:** %s\n", f.Remediation)
			}
			md.WriteString("\n")
		}
	}

	traces := exploit.TracesFor(result.Target.String())
	chainMD := ChainTracesMarkdown(traces)
	if chainMD != "" {
		md.WriteString(chainMD)
		md.WriteString("\n```mermaid\n")
		md.WriteString(ChainTracesMermaid(traces))
		md.WriteString("```\n\n")
	}

	md.WriteString("---\n*Generated by CatchClaw v6.0.0 (Go)*\n")
	return os.WriteFile(path, []byte(md.String()), 0644)
}

