func severityClass(s core.Severity) string {
	switch s {
	case core.Critical:
		return "critical"
	case core.High:
		return "high"
	case core.Medium:
		return "medium"
	case core.Low:
		return "low"
	default:
		return "info"
	}
}

func htmlEscape(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "\"", "&quot;")
	return r.Replace(s)
}

func ExportGraph(graph *core.AttackGraph, nodes map[int][2]string, outputDir, targetHost string, targetPort int) error {
	if outputDir == "" {
		outputDir = "."
	}
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return err
	}

	timestamp := time.Now().Format("20060102_150405")
	targetID := strings.NewReplacer(".", "_", ":", "_").Replace(fmt.Sprintf("%s_%d", targetHost, targetPort))

	mermaid := graph.ToMermaid(nodes)
	mermaidPath := fmt.Sprintf("%s/attack_graph_%s_%s.mmd", outputDir, targetID, timestamp)
	if err := os.WriteFile(mermaidPath, []byte(mermaid), 0644); err != nil {
		return err
	}
	fmt.Printf("\033[32m[+]\033[0m Attack graph exported to %s\n", mermaidPath)
	return nil
}
